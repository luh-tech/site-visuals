// Generates src/generated/*.ts from schema-registry's canonical schemas, so a record that validates against the
// registry is a record the kit's types accept (d-2026-10-16-bt-figure-kit OUT-1). Reads a local schema-registry
// checkout at the tag the kit pins; https://schemas.luh.tech/<path> references resolve to <checkout>/schemas/<path>.
//
//   SR_ROOT=../../../schema-registry npm run gen:types -w @luhtech/figures
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const SR = process.env.SR_ROOT;
if (!SR) throw new Error("SR_ROOT: a schema-registry checkout");
const PIN = JSON.parse(readFileSync(join(here, "..", "package.json"), "utf8")).luhtech.schemaRegistryTag;
const at = execFileSync("git", ["-C", SR, "describe", "--tags", "--exact-match", "HEAD"], { encoding: "utf8" }).trim();
if (at !== PIN) throw new Error(`schema-registry checkout is at ${at}, the kit pins ${PIN}`);

const local = {
  order: 1,
  canRead: /^https:\/\/schemas\.luh\.tech\//,
  read: (file) => readFileSync(join(SR, "schemas", file.url.replace("https://schemas.luh.tech/", "").split("#")[0]), "utf8"),
};
const out = join(here, "..", "src", "generated");
mkdirSync(out, { recursive: true });
const banner = `/* Generated by scripts/gen-types.mjs from schema-registry ${PIN}. Do not edit; regenerate. */`;

for (const [name, path] of [
  ["figure", "content/figure.schema.json"],
  ["brand-identity", "portfolio/brand-identity.schema.json"],
  ["market-family", "portfolio/market-family.schema.json"],
  ["market-cell", "portfolio/market-cell.schema.json"],
]) {
  const schema = JSON.parse(readFileSync(join(SR, "schemas", path), "utf8"));
  const ts = await compile(schema, name, {
    bannerComment: banner,
    cwd: join(SR, "schemas", dirname(path)),
    $refOptions: { resolve: { http: local, file: { order: 2 } } },
    additionalProperties: false,
    style: { singleQuote: false },
  });
  writeFileSync(join(out, `${name}.ts`), ts);
  console.log(`src/generated/${name}.ts`);
}
